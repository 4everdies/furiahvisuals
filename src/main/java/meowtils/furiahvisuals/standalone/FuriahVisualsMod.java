package meowtils.furiahvisuals.standalone;

import meowtils.furiahvisuals.standalone.proxy.CommonProxy;
import net.minecraftforge.fml.common.Mod;
import net.minecraftforge.fml.common.SidedProxy;
import net.minecraftforge.fml.common.event.FMLInitializationEvent;
import net.minecraftforge.fml.common.event.FMLPreInitializationEvent;

@Mod(modid = FuriahVisualsMod.MOD_ID, name = FuriahVisualsMod.NAME, version = FuriahVisualsMod.VERSION,
     clientSideOnly = true, acceptedMinecraftVersions = "[1.8.9]")
public final class FuriahVisualsMod {
    public static final String MOD_ID = "furiahsvisuals";
    public static final String NAME = "Furiah's Visuals";
    public static final String VERSION = "1.3.5-standalone";

    @SidedProxy(clientSide = "meowtils.furiahvisuals.standalone.proxy.ClientProxy",
                serverSide = "meowtils.furiahvisuals.standalone.proxy.CommonProxy")
    public static CommonProxy proxy;

    @Mod.EventHandler
    public void preInit(FMLPreInitializationEvent event) {
        event.getModMetadata().autogenerated = false;
        event.getModMetadata().name = NAME;
        event.getModMetadata().version = VERSION;
        event.getModMetadata().description = "Standalone visual effects and interface for Minecraft 1.8.9.";
    }

    @Mod.EventHandler
    public void init(FMLInitializationEvent event) {
        proxy.initialize();
    }
}
